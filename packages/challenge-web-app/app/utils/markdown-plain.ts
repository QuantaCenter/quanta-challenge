/**
 * Markdown 源码 → 纯文本，用于列表简介等只读场景。
 *
 * 只做语法剥除，不追求渲染级精确：代码块围栏、标题、引用、列表标记、
 * 链接/图片、强调、行内代码、表格分隔、原生 HTML 标签都会被去掉，
 * 只留下可读的正文。
 */
export const markdownToPlainText = (markdown: string): string =>
   markdown
      // 围栏代码块：去掉围栏与语言标注，保留代码内容
      .replace(/^(```|~~~)[\w-]*\n?([\s\S]*?)^\1.*$/gm, '$2')
      // 图片：只留 alt
      .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1')
      // 链接：只留文字
      .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')
      // 原生 HTML 标签（通知正文里的 HTML 本来就不该执行）
      .replace(/<\/?[a-z][^>]*>/gi, '')
      // 标题 / 引用前缀
      .replace(/^\s{0,3}#{1,6}\s+/gm, '')
      .replace(/^\s{0,3}>\s?/gm, '')
      // 任务列表勾选框
      .replace(/^\s*[-*+]\s+\[[ xX]\]\s+/gm, '')
      // 无序 / 有序列表标记
      .replace(/^\s*[-*+]\s+/gm, '')
      .replace(/^\s*\d+[.)]\s+/gm, '')
      // 分隔线
      .replace(/^\s*(?:[-*_]\s*){3,}$/gm, '')
      // 表格：行首尾竖线与单元格分隔符换成空格，分隔行整行去掉
      .replace(/^\s*\|(.+)\|\s*$/gm, '$1')
      .replace(/^\s*\|?[\s:|-]+\|[\s:|-]*$/gm, '')
      .replace(/\|/g, ' ')
      // 强调 / 删除线 / 行内代码
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/\*([^*]+)\*/g, '$1')
      .replace(/__([^_]+)__/g, '$1')
      .replace(/(?<![\w])_([^_]+)_(?![\w])/g, '$1')
      .replace(/~~([^~]+)~~/g, '$1')
      .replace(/`([^`]+)`/g, '$1')
      // 折叠连续空行
      .replace(/\n{3,}/g, '\n\n')
      .trim();
